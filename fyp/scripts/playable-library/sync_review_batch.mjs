/** Local-only review mirror. Copies runtime packages, never original ZIPs or private workflow files. */
import { readFile, writeFile, mkdir, cp, stat, lstat } from 'node:fs/promises';
import { resolve, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const project = fileURLToPath(new URL('../../', import.meta.url));
const review = resolve(project, '../2026-10-05-all-files-review');
const index = await readFile(resolve(review, 'index.html'), 'utf8');
const base = JSON.parse(index.match(/const games = (\[.*?\]);/s)[1]);
const extras = await readFile(resolve(review, 'batch-1012-games.js'), 'utf8');
const imported = JSON.parse(extras.match(/window\.PlayableImportedGames = (\[.*?\]);/s)[1]);
const { normalize } = createRequire(import.meta.url)(resolve(review, 'review-catalog.js'));
const games = normalize([...base, ...imported]);
const catalog = {};
const allowed = new Set(['.html','.js','.mjs','.css','.json','.png','.jpg','.jpeg','.webp','.gif','.svg','.woff','.woff2','.ttf','.otf','.mp3','.wav','.ogg','.m4a','.mp4','.webm','.wasm','.tflite','.ico','.txt']);
for (const game of games) {
  if (!/^[a-zA-Z0-9_-]+$/.test(game.taskId)) throw new Error('Invalid task ID');
  const source = resolve(review, game.src.split('?')[0]);
  if (!source.startsWith(resolve(project,'..') + '/')) throw new Error('Entry outside the approved working folders');
  if (!(await stat(source)).isFile()) throw new Error('Missing entry: ' + game.number);
  const target = resolve(project, 'public/resource/playable-batch', game.taskId);
  await mkdir(target, { recursive: true });
  await cp(dirname(source), target, { recursive: true, filter: async file => {
    const name = basename(file);
    if (name.startsWith('.') || ['node_modules','test','tests','baseline','evidence','feedback-tracking'].includes(name)) return false;
    const info = await lstat(file);
    if (info.isSymbolicLink()) return false;
    return info.isDirectory() || allowed.has(extname(file).toLowerCase());
  } });
  const html = await readFile(source, 'utf8');
  // Preserve the explicit controls revision, not arbitrary source query data.
  const controlsRevision = new URLSearchParams(game.src.split('?')[1] || '').get('controls');
  const conversionHost = game.source === 'effecthouse-conversion-20261020' ? '&host=fyp' : '';
  const adapter = '<script src="/resource/playable-batch/review-host.js"></script><script src="/resource/playable-feed/pocket-host.js" data-seed-random="off"></script>';
  await writeFile(resolve(target, basename(source)), html.replace(/<head>/i, '<head>\n' + adapter));
  try {
    const italianSource=source.replace(/\.html$/,'.it.html');
    const italian=await readFile(italianSource,'utf8');
    await writeFile(resolve(target,basename(italianSource)),italian.replace(/<head>/i,'<head>\n'+adapter));
  } catch(error) { if(error.code!=='ENOENT')throw error; }
  catalog['playable-batch-' + game.taskId] = {
    src: '/resource/playable-batch/' + game.taskId + '/' + basename(source) + '?review=batch-20261013-1' + (controlsRevision ? '&controls=' + encodeURIComponent(controlsRevision) : '') + conversionHost,
    title: String(game.number) + '. ' + game.name,
    description: String(game.number) + '. ' + game.name,
    taskId: game.taskId, number: game.number,
  };
}
await writeFile(resolve(project,'src/page/home/components/playable_batch_games.ts'),
  '/** Generated by sync_review_batch.mjs from the local review list; no ZIP paths or private metadata. */\nexport const PLAYABLE_BATCH_GAMES = ' + JSON.stringify(catalog,null,2) + ' as const;\n\nexport const isBatchReview = () => new URLSearchParams(window.location.search).get("review") === "batch";\n');
console.log('Mirrored all ' + games.length + ' supplied review games, numbered 1–' + games.length + '. No game files deleted. No upload performed.');
